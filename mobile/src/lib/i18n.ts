/** Name of one ladder step; in English, 'letter' is the small-letters step. */
export function levelLabel(t: Strings, language: Language, level: Level): string {
  return language === 'en' && level === 'letter' ? t.levelNames.small : t.levelNames[level];
}

/** Name of a placed level (0 = beginner) on the language's ladder. */
export function placedLabel(t: Strings, language: Language, placed: PlacedLevel): string {
  const step = placedStep(placed, language);
  return step ? levelLabel(t, language, step) : t.levelNames.beginner;
}
